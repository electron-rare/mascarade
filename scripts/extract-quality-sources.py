# Run all extractors
extractors = [
    ("esp-idf", extract_esp_idf),
    ("pico", extract_pico),
    ("cmsis-dsp", extract_cmsis_dsp),
    ("ch32fun", extract_ch32fun),
    ("spice-datasets", extract_spice),
    ("liquid-dsp", extract_liquid_dsp),
    ("ngspice", extract_ngspice),
]

grand_total = 0
for name, fn in extractors:
    print(f"\n=== Extracting: {name} ===")
    results = fn()

    # Dedup against existing
    deduped = []
    dupes = 0
    for r in results:
        text = " ".join(c.get("value", "") for c in r["conversations"])
        h = hashlib.md5(text[:500].encode()).hexdigest()
        if h in existing_hashes:
            dupes += 1
            continue
        existing_hashes.add(h)
        deduped.append(r)

    # Quality filter
    quality = []
    for r in deduped:
        answer = " ".join(c.get("value", "") for c in r["conversations"] if c.get("from") in ("gpt", "assistant"))
        if len(answer) < 100:
            continue
        quality.append(r)

    # Save
    output = os.path.join(OUTPUT_DIR, f"{name}_quality.jsonl")
    with open(output, "w") as f:
        for r in quality:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    print(f"  Extracted: {len(results)}, Deduped: {dupes}, Quality filtered: {len(deduped)-len(quality)}, FINAL: {len(quality)}")
    grand_total += len(quality)

# Summary
print(f"\n{'='*60}")
print(f"TOTAL QUALITY EXAMPLES: {grand_total}")
print(f"{'='*60}")
for fn in sorted(os.listdir(OUTPUT_DIR)):
    if fn.endswith(".jsonl"):
        lines = sum(1 for _ in open(os.path.join(OUTPUT_DIR, fn)))
        print(f"  {fn}: {lines}")
