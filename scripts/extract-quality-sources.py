"""Extract quality code from cloned repos and convert to training datasets.

For each source:
1. Find relevant code files (.c, .h, .py, .rs, .spice, .sch)
2. Extract with context (README, comments, file path as metadata)
3. Quality filter: min length, has real code, not auto-generated
4. Convert to conversations format with contextual Q&A
5. Dedup against existing datasets
"""

import json
import os
import hashlib

SOURCES_DIR = "finetune/sources"
OUTPUT_DIR = "finetune/datasets/quality_sources"
os.makedirs(OUTPUT_DIR, exist_ok=True)

# Existing hashes for cross-dedup
existing_hashes = set()
for d in ["finetune/datasets", "finetune/datasets/cleaned_final", "finetune/datasets/hf_imports"]:
    if not os.path.isdir(d):
        continue
    for fn in os.listdir(d):
        if not fn.endswith(".jsonl"):
            continue
        try:
            with open(os.path.join(d, fn)) as f:
                for line in f:
                    if line.strip():
                        h = hashlib.md5(line.strip()[:500].encode()).hexdigest()
                        existing_hashes.add(h)
        except:
            pass

print(f"Loaded {len(existing_hashes)} existing hashes for cross-dedup")


def read_file_safe(path, max_size=50000):
    try:
        with open(path, "r", errors="replace") as f:
            return f.read(max_size)
    except:
        return ""


def find_readme(directory):
    """Find README in directory or parent."""
    for name in ["README.md", "README.rst", "README.txt", "README"]:
        p = os.path.join(directory, name)
        if os.path.exists(p):
            return read_file_safe(p, 2000)
    return ""


def is_autogenerated(content):
    """Detect auto-generated files."""
    markers = ["DO NOT EDIT", "AUTO-GENERATED", "This file is generated", "Generated by", "machine-generated"]
    first_lines = content[:500].lower()
    return any(m.lower() in first_lines for m in markers)


def extract_esp_idf():
    """Extract ESP-IDF examples as Q&A pairs."""
    base = os.path.join(SOURCES_DIR, "esp-idf-examples", "examples")
    if not os.path.isdir(base):
        print("ESP-IDF not found"); return []

    results = []
    for root, dirs, files in os.walk(base):
        # Find main source file
        main_c = None
        for f in files:
            if f in ("main.c", "app_main.c") or (f.endswith(".c") and "main" in f):
                main_c = os.path.join(root, f)
                break
        if not main_c:
            continue

        code = read_file_safe(main_c)
        if len(code) < 100 or is_autogenerated(code):
            continue

        # Get context
        readme = find_readme(root) or find_readme(os.path.dirname(root))
        rel_path = os.path.relpath(root, base)
        rel_path.split(os.sep)[0] if os.sep in rel_path else rel_path

        # Build Q&A
        question = f"Write an ESP-IDF example for: {rel_path.replace(os.sep, ' / ')}"
        if readme:
            question += f"\n\nContext from README:\n{readme[:500]}"

        answer = f"Here is the ESP-IDF implementation ({rel_path}):\n\n```c\n{code[:3000]}\n```"

        results.append({
            "conversations": [
                {"from": "system", "value": "You are an expert ESP-IDF developer. You write production-grade ESP32 firmware."},
                {"from": "human", "value": question},
                {"from": "gpt", "value": answer},
            ],
            "domain": "esp-idf",
            "source": "espressif/esp-idf",
            "license": "Apache-2.0",
            "path": rel_path,
        })

    return results


